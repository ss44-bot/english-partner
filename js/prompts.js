EP.scenePrompt = function (topic) {
  return `یک صحنهٔ بصری برای یادگیری بساز دربارهٔ: ${topic || 'موضوع فعلی'}.\n` + EP.PROMPT_LIBRARY.find(p => p.id === 'scene').body;
};

EP.pagePrompt = function (mode, book) {
  const map = {
    single: EP.PROMPT_LIBRARY.find(p => p.id === 'page-single').body,
    cross: EP.PROMPT_LIBRARY.find(p => p.id === 'page-cross').body,
    cluster: 'چند منبع/عکس را خوشه‌ای روی یک موضوع واحد تحلیل کن و یک درس یکپارچه بساز. همپوشانی و تفاوت سطح را جدول کن.'
  };
  let t = map[mode] || map.single;
  if (book) t = `کتاب/واحد اعلام‌شده: ${book}\n` + t;
  return t;
};
